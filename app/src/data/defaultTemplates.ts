/**
 * 细分隔线：用细长色块字段实现。
 * fixedText 为空串 → 不参与 Excel 映射、自动匹配与缺失高亮。
 */
function hairline(
  id: string,
  rect: { x: number; y: number; width: number; height: number },
  color = LINE,
): TemplateField {
  return {
    id,
    label: '分隔线',
    type: 'text',
    ...rect,
    fixedText: '',
    background: color,
    padding: 0,
    maxLines: 1,
  }
}

