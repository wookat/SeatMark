/**
 * 不干胶/模切分切纸型库（单一数据源）：
 * - /studio 纸张设置「按纸型选择」：选型号自动锁定行列/尺寸/边距/间距；
 * - /papers 与 /papers/:slug SEO 落地页：规格参数 + 适用模板推荐；
 * - 几何换算见 src/utils/labelPaper.ts（边距由居中排版推导或按规格显式值，单测覆盖）。
 *
 * 规格说明：以国内电商主流 SKU 为准——A4（210 × 297 mm）满切与圆角模切
 * 覆盖汉唐/鸿诺/龙诚海等通用货号，A3/A5 收录整版背胶纸；avery-* 系列为
 * US Letter（215.9 × 279.4 mm）美标模切，边距/间距按 Avery 官方模切数据。
 */

export type PaperCorner = 'square' | 'rounded'

export interface LabelPaperSpec {
  /** 路由 slug，如 a4-8up */
  slug: string
  /** 展示名，如「A4 8格（2 列 × 4 行）」 */
  name: string
  /** 常见电商叫法 / 别名 */
  aliases: string[]
  cols: number
  rows: number
  /** 单枚标签尺寸（mm） */
  labelWidth: number
  labelHeight: number
  /** 标签间距（mm），满切规格为 0 */
  gapX: number
  gapY: number
  /** 纸张尺寸（mm），缺省为 A4；美标 Avery 规格为 Letter 215.9×279.4 */
  sheetWidth?: number
  sheetHeight?: number
  /**
   * 显式边距（mm）：缺省时由居中排版推导；
   * Avery 等模切纸的左右/上下不对称边距必须显式给出以对版
   */
  marginLeft?: number
  marginRight?: number
  marginTop?: number
  marginBottom?: number
  /** 对折纸型的压痕方向：horizontal=每格中线横向压痕；vertical=每格中线纵向压痕（Avery 对折桌牌用） */
  fold?: 'horizontal' | 'vertical'
  corner: PaperCorner
  /** 圆角半径（mm），仅圆角规格 */
  cornerRadius?: number
  /** 一句话描述（列表卡片与 meta description 用） */
  description: string
  /** 典型用途 */
  uses: string[]
  /** 适用内置模板 id（对应 /templates/:slug） */
  recommendedTemplates: string[]
}

export const LABEL_PAPER_SHEET = { width: 210, height: 297 } as const

/** 美标 Letter 纸尺寸（8.5 × 11 in） */
export const LETTER_PAPER_SHEET = { width: 215.9, height: 279.4 } as const

/** 纸型实际用纸尺寸：缺省 A4 */
export function sheetOf(spec: LabelPaperSpec): { width: number; height: number } {
  return { width: spec.sheetWidth ?? LABEL_PAPER_SHEET.width, height: spec.sheetHeight ?? LABEL_PAPER_SHEET.height }
}

/** 纸张尺寸分类键：列表筛选 / 详情页纸张名 / SEO 共用 */
export type SheetKey = 'A4' | 'A3' | 'A5' | 'US Letter' | '其他'

export function sheetKeyOf(spec: LabelPaperSpec): SheetKey {
  const { width, height } = sheetOf(spec)
  if (width === 210 && height === 297) return 'A4'
  if (width === 297 && height === 420) return 'A3'
  if (width === 148 && height === 210) return 'A5'
  if (width === 215.9 && height === 279.4) return 'US Letter'
  return '其他'
}

/** 版式分类键：整版 / 横条 / 竖条 / 多格 / 对折 / 圆形 */
export type PaperForm = '整版' | '横条' | '竖条' | '多格' | '对折' | '圆形'

export function formOf(spec: LabelPaperSpec): PaperForm {
  if (spec.fold) return '对折'
  const corner = spec.cornerRadius ?? 0
  if (spec.corner === 'rounded' && corner * 2 >= Math.min(spec.labelWidth, spec.labelHeight)) {
    return '圆形'
  }
  if (spec.cols * spec.rows === 1) return '整版'
  if (spec.cols === 1) return '横条'
  if (spec.rows === 1) return '竖条'
  return '多格'
}

